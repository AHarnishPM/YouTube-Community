(function () {
  const BUBBLE_ID = "ytc-hello-bubble";

  function injectBubble() {
    if (document.getElementById(BUBBLE_ID)) return;

    const timeDisplay = document.querySelector(".ytp-time-display");
    if (!timeDisplay) return;

    const bubble = document.createElement("span");
    bubble.id = BUBBLE_ID;
    bubble.className = "ytc-bubble";

    const inner = document.createElement("span");
    inner.className = "ytc-bubble-inner";
    inner.textContent = "Hello World";
    bubble.appendChild(inner);

    timeDisplay.insertAdjacentElement("afterend", bubble);
  }

  const observer = new MutationObserver(injectBubble);
  observer.observe(document.body, { childList: true, subtree: true });

  injectBubble();

  let lastVideoId = null;

  function formatTime(seconds) {
    const m = Math.floor(seconds / 60);
    const s = Math.floor(seconds % 60).toString().padStart(2, "0");
    return `${m}:${s}`;
  }

  async function logTranscript() {
    const videoId = new URLSearchParams(location.search).get("v");
    if (location.pathname !== "/watch" || !videoId || videoId === lastVideoId) return;
    lastVideoId = videoId;

    try {
      const transcript = await fetchTranscript(videoId);
      if (!transcript) {
        console.log(`[YouTube Community] No transcript available for ${videoId}`);
        return;
      }
      const preview = transcript.lines
        .slice(0, 100)
        .map((line) => `[${formatTime(line.start)}] ${line.text}`)
        .join("\n");
      console.log(
        `[YouTube Community] Transcript for ${videoId} (${transcript.languageCode}` +
          `${transcript.autoGenerated ? ", auto-generated" : ""}, ${transcript.lines.length} lines):\n${preview}`
      );

      const result = await chrome.runtime.sendMessage({ type: "saveTranscript", transcript });
      if (result.ok) {
        console.log(`[YouTube Community] Saved transcript for ${videoId} to Firebase`);
      } else {
        console.error(`[YouTube Community] Failed to save transcript for ${videoId}: ${result.error}`);
      }
    } catch (err) {
      console.error(`[YouTube Community] Transcript error for ${videoId}`, err);
    }
  }

  // YouTube is a single-page app, so in-app navigation to another video doesn't reload the content script.
  document.addEventListener("yt-navigate-finish", logTranscript);
  logTranscript();
})();
