// Player requests use the ANDROID client because WEB-client ones are rejected without a proof-of-origin token.
const INNERTUBE_CLIENT = { clientName: "ANDROID", clientVersion: "20.10.38" };
const WEB_CLIENT = { clientName: "WEB", clientVersion: "2.20251001.00.00" };

// durationSeconds is null when YouTube doesn't report a length (e.g. live streams).
async function fetchVideoInfo(videoId) {
  const res = await fetch("/youtubei/v1/player?prettyPrint=false", {
    method: "POST",
    credentials: "omit",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ context: { client: INNERTUBE_CLIENT }, videoId }),
  });
  if (!res.ok) throw new Error(`player request failed: ${res.status}`);
  const data = await res.json();
  return {
    durationSeconds: Number(data.videoDetails?.lengthSeconds) || null,
    captionTracks: data.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [],
  };
}

function pickTrack(tracks) {
  const lang = navigator.language.split("-")[0];
  const inLang = tracks.filter((t) => t.languageCode.split("-")[0] === lang);
  return inLang.find((t) => t.kind !== "asr") ?? inLang[0] ?? tracks[0];
}

// Resolves to null when the video has no captions; line times are in seconds.
async function fetchTranscript(tracks) {
  if (tracks.length === 0) return null;

  const track = pickTrack(tracks);
  const url = new URL(track.baseUrl, location.origin);
  url.searchParams.set("fmt", "json3");

  const res = await fetch(url, { credentials: "omit" });
  if (!res.ok) throw new Error(`caption request failed: ${res.status}`);
  const data = await res.json();

  const lines = (data.events ?? [])
    .filter((e) => e.segs)
    .map((e) => ({
      start: e.tStartMs / 1000,
      duration: (e.dDurationMs ?? 0) / 1000,
      text: e.segs.map((s) => s.utf8).join("").replace(/\s+/g, " ").trim(),
    }))
    .filter((line) => line.text);

  return { languageCode: track.languageCode, autoGenerated: track.kind === "asr", lines };
}

function findKey(node, key) {
  if (node === null || typeof node !== "object") return undefined;
  if (key in node) return node[key];
  for (const child of Object.values(node)) {
    const found = findKey(child, key);
    if (found !== undefined) return found;
  }
  return undefined;
}

function chaptersForMarkerKey(markersMap, key, durationSeconds) {
  const markers = markersMap.find((m) => m.key === key);
  const starts = (markers?.value?.chapters ?? []).map((c) => ({
    title: c.chapterRenderer.title.simpleText,
    start: c.chapterRenderer.timeRangeStartMillis / 1000,
  }));

  return starts.map((chapter, i) => {
    const end = starts[i + 1]?.start ?? durationSeconds;
    return end === null ? chapter : { ...chapter, duration: Math.round((end - chapter.start) * 1000) / 1000 };
  });
}

// creator: chapters written in the video's description. auto: chapters YouTube generated.
// Either is [] when the video doesn't have that kind.
async function fetchChapters(videoId, durationSeconds) {
  const res = await fetch("/youtubei/v1/next?prettyPrint=false", {
    method: "POST",
    credentials: "omit",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ context: { client: WEB_CLIENT }, videoId }),
  });
  if (!res.ok) throw new Error(`next request failed: ${res.status}`);
  const data = await res.json();

  const markersMap = findKey(data, "markersMap") ?? [];
  return {
    creator: chaptersForMarkerKey(markersMap, "DESCRIPTION_CHAPTERS", durationSeconds),
    auto: chaptersForMarkerKey(markersMap, "AUTO_CHAPTERS", durationSeconds),
  };
}
