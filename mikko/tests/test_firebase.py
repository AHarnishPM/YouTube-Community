import unittest
from claim_detection.firebase import convert
from claim_detection.core import Segment, detect
from claim_detection.detectors import RuleDetector


class FirebaseTests(unittest.TestCase):
    def setUp(self):
        self.transcript = {"languageCode":"en", "autoGenerated":True, "fetchedAt":123,
                           "lines":[{"start":1.5,"duration":2,"text":"The study found"},
                                    {"start":3.5,"duration":3,"text":"a 25 percent increase."}]}

    def test_lines_stay_separate_with_original_times(self):
        rows = convert(self.transcript, "video")
        self.assertEqual(len(rows), 2)
        self.assertEqual(rows[0]["text"], "The study found")
        self.assertEqual(rows[0]["end"], 3.5)
        self.assertEqual(rows[1]["source_line_index"], 1)
        result = detect(Segment.from_dict(rows[1]), RuleDetector())
        self.assertEqual(result["segment_id"], rows[1]["segment_id"])

    def test_refetch_stable_but_changed_text_invalidates_id(self):
        before = convert(self.transcript, "video")
        self.transcript["fetchedAt"] = 456
        self.assertEqual(before, convert(self.transcript, "video"))
        self.transcript["lines"][0]["text"] = "Different"
        after = convert(self.transcript, "video")
        self.assertNotEqual(before[0]["segment_id"], after[0]["segment_id"])
        self.assertEqual(before[1]["segment_id"], after[1]["segment_id"])

    def test_video_id_from_extension_message_or_explicit_path(self):
        with self.assertRaises(ValueError): convert(self.transcript)
        self.transcript["videoId"] = "video"
        self.assertEqual(convert(self.transcript), convert(self.transcript, "video"))
        with self.assertRaises(ValueError): convert(self.transcript, "other")

    def test_missing_or_zero_duration_is_explicit(self):
        for duration in [0, -1, True, float("nan"), float("inf")]:
            self.transcript["lines"][0]["duration"] = duration
            with self.subTest(duration=duration), self.assertRaises(ValueError):
                convert(self.transcript, "video")

    def test_invalid_lines(self):
        for lines in [None, [], [None], [{"start":0,"text":"missing duration"}]]:
            self.transcript["lines"] = lines
            with self.subTest(lines=lines), self.assertRaises(ValueError):
                convert(self.transcript, "video")
